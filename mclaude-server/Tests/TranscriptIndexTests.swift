import XCTest
@testable import mclaude_server

final class TranscriptIndexTests: XCTestCase {
    private var dir: String!

    override func setUp() {
        dir = NSTemporaryDirectory() + "transcript-index-\(UUID().uuidString)"
        try? FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
    }

    override func tearDown() {
        try? FileManager.default.removeItem(atPath: dir)
    }

    private func line(_ obj: [String: Any]) -> String {
        String(data: try! JSONSerialization.data(withJSONObject: obj), encoding: .utf8)!
    }

    private func user(_ content: Any, extra: [String: Any] = [:]) -> String {
        var obj: [String: Any] = ["type": "user", "isSidechain": false, "cwd": "/tmp/proj",
                                  "message": ["role": "user", "content": content]]
        obj.merge(extra) { _, b in b }
        return line(obj)
    }

    private func title(_ t: String) -> String { line(["type": "ai-title", "aiTitle": t, "sessionId": "x"]) }

    @discardableResult
    private func write(project: String, id: String, lines: [String]) -> String {
        let p = "\(dir!)/\(project)"
        try? FileManager.default.createDirectory(atPath: p, withIntermediateDirectories: true)
        let path = "\(p)/\(id).jsonl"
        FileManager.default.createFile(atPath: path, contents: Data((lines.joined(separator: "\n") + "\n").utf8))
        return path
    }

    private func parse(_ lines: [String]) -> (cwd: String, firstPrompt: String?, aiTitle: String?)? {
        TranscriptIndex.parse(head: Data((lines.joined(separator: "\n") + "\n").utf8), tail: nil)
    }

    // MARK: - Prompt filtering

    func testSkipsMetaSidechainCommandsAndToolResults() {
        let r = parse([
            line(["type": "queue-operation", "operation": "enqueue"]),
            user("<command-name>/clear</command-name>"),
            user("<local-command-stdout>ok</local-command-stdout>"),
            user("<command-message>init</command-message>"),
            user("Caveat: the messages below were generated by the user while running local commands."),
            user("meta prompt", extra: ["isMeta": true]),
            user("side prompt", extra: ["isSidechain": true]),
            user([["type": "tool_result", "tool_use_id": "t1", "content": "out"]]),
            user("summary", extra: ["isCompactSummary": true]),
            line(["type": "assistant", "cwd": "/tmp/proj", "message": ["content": [["type": "text", "text": "hi"]]]]),
            user("  Fix   the\n\nlogin   bug  "),
            user("second prompt"),
        ])
        XCTAssertEqual(r?.firstPrompt, "Fix the login bug")
    }

    func testTextBlockArrayPromptAndCap() {
        let long = String(repeating: "word ", count: 100)
        let r = parse([user([["type": "image", "source": [:]], ["type": "text", "text": long]])])
        XCTAssertEqual(r?.firstPrompt?.count, 200)
        XCTAssertTrue(r?.firstPrompt?.hasPrefix("word word") ?? false)
    }

    func testNoRealPrompt() {
        let r = parse([user("<command-name>/model</command-name>"), user("x", extra: ["isMeta": true])])
        XCTAssertNotNil(r)
        XCTAssertNil(r?.firstPrompt)
    }

    // MARK: - cwd and ai-title

    func testCwdFromFirstLineWithOne() {
        let r = parse([
            line(["type": "queue-operation", "operation": "enqueue"]),
            line(["type": "attachment", "cwd": "/Users/me/first"]),
            user("hello", extra: ["cwd": "/Users/me/second"]),
        ])
        XCTAssertEqual(r?.cwd, "/Users/me/first")
    }

    func testNoCwdMeansNil() {
        XCTAssertNil(parse([line(["type": "user", "message": ["content": "hi"]]), title("T")]))
    }

    func testLastAiTitleWins() {
        let r = parse([user("go"), title("Old title"), title("Old title"), title("New title")])
        XCTAssertEqual(r?.aiTitle, "New title")
    }

    func testBigFileReadsHeadAndTailOnly() throws {
        // Head: cwd + prompt + an early title. Middle: filler bigger than both windows. Tail: later title.
        let filler = line(["type": "assistant", "message": ["content": [["type": "text", "text": String(repeating: "z", count: 1000)]]]])
        var lines = [user("first real prompt"), title("Early")]
        lines += Array(repeating: filler, count: 700)                       // ~700 KB
        lines += [title("Middle-ish")] + Array(repeating: filler, count: 400) + [title("Late"), filler]
        let path = write(project: "-tmp-proj", id: UUID().uuidString.lowercased(), lines: lines)
        let size = (try FileManager.default.attributesOfItem(atPath: path)[.size] as! NSNumber).intValue
        let windows = try XCTUnwrap(TranscriptIndex.readWindows(path: path, size: size))
        XCTAssertEqual(windows.head.count, TranscriptIndex.window)
        XCTAssertNotNil(windows.tail)
        let r = TranscriptIndex.parse(head: windows.head, tail: windows.tail)
        XCTAssertEqual(r?.cwd, "/tmp/proj")
        XCTAssertEqual(r?.firstPrompt, "first real prompt")
        XCTAssertEqual(r?.aiTitle, "Late")
    }

    // MARK: - Listing

    func testListFiltersSortsAndNames() async throws {
        let a = UUID().uuidString.lowercased(), b = UUID().uuidString.lowercased()
        let c = UUID().uuidString.lowercased(), d = UUID().uuidString.lowercased()
        let pa = write(project: "-tmp-proj", id: a, lines: [user("prompt a"), title("Title A")])
        let pb = write(project: "-tmp-proj", id: b, lines: [user("prompt b")])
        write(project: "-tmp-proj", id: c, lines: [user("<command-name>/clear</command-name>")])   // no real prompt
        write(project: "-tmp-other", id: d, lines: [user("open one")])                              // open session
        // Subagent transcripts below the top level don't count
        write(project: "-tmp-proj/\(a)/subagents", id: UUID().uuidString.lowercased(), lines: [user("sub")])
        let old = Date().addingTimeInterval(-3600)
        try FileManager.default.setAttributes([.modificationDate: old], ofItemAtPath: pa)
        try FileManager.default.setAttributes([.modificationDate: old.addingTimeInterval(-60)], ofItemAtPath: pb)

        let index = TranscriptIndex(projectsDir: dir)
        let list = await index.list(open: [d], endedNames: [b: "Ended name"])
        XCTAssertEqual(list.map(\.id), [a, b])
        XCTAssertEqual(list[0].name, "Title A")
        XCTAssertEqual(list[0].projectName, "proj")
        XCTAssertEqual(list[0].firstPrompt, "prompt a")
        XCTAssertFalse(list[0].inUse)
        XCTAssertEqual(list[1].name, "Ended name")

        // Cached until size/mtime change; a fresh write shows up and is in use
        write(project: "-tmp-proj", id: b, lines: [user("prompt b"), title("B title")])
        let again = await index.list(open: [], endedNames: [:])
        XCTAssertEqual(again.first?.id, b)
        XCTAssertEqual(again.first?.name, "B title")
        XCTAssertEqual(again.first?.inUse, true)
        XCTAssertEqual(again.count, 3)

        let found = await index.find(id: a)
        XCTAssertEqual(found?.cwd, "/tmp/proj")
        let missing = await index.find(id: "../../etc/passwd")
        XCTAssertNil(missing)
    }

    // MARK: - SessionManager resume / end

    func testResumeOpenMissingDirAndEndedNames() async throws {
        let stateDir = "\(dir!)/state", cwd = "\(dir!)/work"
        try FileManager.default.createDirectory(atPath: cwd, withIntermediateDirectories: true)
        let id = UUID().uuidString.lowercased()
        let path = write(project: "-x", id: id, lines: [user("hello there")])
        let t = TranscriptSummary(id: id, path: path, cwd: cwd, firstPrompt: "hello there", aiTitle: nil,
                                  modifiedAt: Date())
        let manager = SessionManager(stateDir: stateDir)

        let gone = TranscriptSummary(id: UUID().uuidString.lowercased(), path: path, cwd: "\(dir!)/nope",
                                     firstPrompt: nil, aiTitle: nil, modifiedAt: Date())
        let missing = await manager.resumeTranscript(gone, token: nil)
        XCTAssertEqual(missing, .directoryMissing)

        let first = await manager.resumeTranscript(t, token: "tok")
        XCTAssertEqual(first, .resumed("s1"))
        let again = await manager.resumeTranscript(t, token: nil)
        XCTAssertEqual(again, .alreadyOpen("s1"))
        XCTAssertEqual(manager.resumeState.read().open[id], "s1")
        let session = await manager.getSession(id: "s1")
        XCTAssertEqual(session?.name, "hello there")
        XCTAssertEqual(session?.pid, 0)                          // Claude starts on the first message

        _ = await manager.setName(id: "s1", name: "Renamed")
        let deleted = await manager.deleteSession(id: "s1")
        XCTAssertTrue(deleted)
        XCTAssertNil(manager.resumeState.read().open[id])
        XCTAssertEqual(manager.resumeState.read().endedNames[id], "Renamed")

        // endedNames survives a restart, and resuming uses then clears it
        let reloaded = SessionManager(stateDir: stateDir)
        await reloaded.start()
        XCTAssertEqual(reloaded.resumeState.read().endedNames[id], "Renamed")
        let resumed = await reloaded.resumeTranscript(t, token: nil)
        XCTAssertEqual(resumed, .resumed("s2"))
        let renamed = await reloaded.getSession(id: "s2")
        XCTAssertEqual(renamed?.name, "Renamed")
        XCTAssertNil(reloaded.resumeState.read().endedNames[id])
    }
}
